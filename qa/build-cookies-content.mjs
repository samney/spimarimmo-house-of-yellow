// Cookies: normalize the crawled Complianz policy document into
// lib/content/cookies-policy.ts — verbatim copy, sanitized markup, split at
// the embedded consent widget (replaced by our React ConsentPreferences).

import fs from "node:fs";

const data = JSON.parse(fs.readFileSync("qa/cookies-data.json", "utf8"));
let html = data.docHTML;

// strip outer #cmplz-document wrapper
html = html.replace(/^<div id="cmplz-document"[^>]*>/, "").replace(/<\/div>\s*$/, "");

// drop the nojavascript notice
html = removeBalancedDiv(html, 'id="cmplz-manage-consent-container-nojavascript"');
// replace the live widget with a marker
html = removeBalancedDiv(html, 'id="cmplz-manage-consent-container"', "<!--WIDGET-->");

// strip comments (except our marker), style attrs, data attrs
html = html
  .replace(/<!--(?!WIDGET)[\s\S]*?-->/g, "")
  .replace(/\s(?:style|size|value|aria-expanded|aria-controls|aria-labelledby|data-[\w-]+)="[^"]*"/g, "")
  .replace(/&nbsp;/g, " ")
  .replace(/\s+\n/g, "\n")
  .trim();

// sanitize: this snapshot renders via dangerouslySetInnerHTML, so enforce
// that no active content survives even though the source is a static crawl.
html = html
  .replace(/<(script|style|iframe|object|embed|form)\b[\s\S]*?<\/\1>/gi, "")
  .replace(/<(script|iframe|object|embed|link|meta)\b[^>]*\/?>/gi, "")
  .replace(/\son\w+="[^"]*"/gi, "")
  .replace(/\shref="\s*javascript:[^"]*"/gi, ' href="#"');
const banned = html.match(/<(script|iframe|object|embed)\b|javascript:|\son\w+=/i);
if (banned) throw new Error("sanitizer left active content: " + banned[0]);

function removeBalancedDiv(src, attrNeedle, replacement = "") {
  const attr = src.indexOf(attrNeedle);
  if (attr === -1) return src;
  const start = src.lastIndexOf("<div", attr);
  let i = src.indexOf(">", attr) + 1;
  let depth = 1;
  const re = /<\/?div\b/g;
  re.lastIndex = i;
  let m;
  while ((m = re.exec(src))) {
    depth += m[0] === "<div" ? 1 : -1;
    if (depth === 0) {
      const end = src.indexOf(">", m.index) + 1;
      return src.slice(0, start) + replacement + src.slice(end);
    }
  }
  return src;
}

const [before, after] = html.split("<!--WIDGET-->");
if (after === undefined) throw new Error("widget marker missing");

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const out = `/* Verbatim Complianz cookie-policy document from the live site
   (crawled 2026-07-31, "last updated on 7 October 2025"). Split where the
   reference embeds its consent-management widget; ours renders there.
   Generated by qa/build-cookies-content.mjs — do not hand-edit. */

export const COOKIES_TITLE = "Cookies - HOY | House Of Yellow";

export const COOKIES_POLICY_BEFORE_WIDGET = \`${esc(before.trim())}\`;

export const COOKIES_POLICY_AFTER_WIDGET = \`${esc(after.trim())}\`;
`;
fs.writeFileSync("lib/content/cookies-policy.ts", out);
console.log(
  `ok before=${before.length} after=${after.length} -> lib/content/cookies-policy.ts`,
);
